function structuredData(seo) {
  return {
    '@context': 'https://schema.org',
    '@type': 'SoftwareApplication',
    'name': 'JOSHUA',
    'applicationCategory': 'GameApplication',
    'operatingSystem': 'Web',
    'isAccessibleForFree': true,
    'author': { '@type': 'Person', 'name': 'Marco Iannacone' },
    'description': seo.jsonldDescription,
    'url': seo.url,
    'inLanguage': seo.lang,
    'license': 'https://www.gnu.org/licenses/agpl-3.0.html',
    'softwareVersion': version(),
    'keywords': 'WarGames, interactive fiction, human-machine decision making, automation'
  };
}

// JSON-LD is emitted inline. A <script type="application/ld+json"> element is a
// non-executable "data block" (not JavaScript), so it does not trigger CSP
// script-src enforcement — verified in Chromium and WebKit. The strict
// default-src 'self' CSP therefore stays intact with no 'unsafe-inline' and no
// hash.
function seoBlock(seo) {
  const jsonld = JSON.stringify(structuredData(seo));
  return [
    `<link rel="canonical" href="${seo.url}">`,
    `<link rel="alternate" hreflang="en" href="${SEO_EN_URL}">`,
    `<link rel="alternate" hreflang="it" href="${SEO_IT_URL}">`,
    `<link rel="alternate" hreflang="x-default" href="${SEO_EN_URL}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:title" content="${seo.title}">`,
    `<meta property="og:description" content="${seo.description}">`,
    `<meta property="og:url" content="${seo.url}">`,
    `<meta property="og:site_name" content="pippo.com">`,
    '<script type="application/ld+json">' + jsonld + '</script>'
  ].join('\n  ');
}

function injectSeoMetadata(htmlPath, seo) {
  let html = fs.readFileSync(htmlPath, 'utf8');
  html = html.replace(/<title>[^<]*<\/title>/, `<title>${seo.title}</title>`);
  html = html.replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${seo.description}">`);
  if (seo.lang === 'it') {
    html = html.replace('<html lang="en">', '<html lang="it">');
  }
  html = html.replace('<!-- SEO_META -->', seoBlock(seo));
  fs.writeFileSync(htmlPath, html);
}

function buildStandalone() {
  const dest = path.join(DIST, 'standalone');
  copyDir(SRC, dest);
  return dest;
}

function buildPippo() {
  const enDir = path.join(DIST, 'pippo.com', 'human-systems', 'interactive-fiction', 'joshua');
  const itDir = path.join(DIST, 'pippo.com', 'it', 'human-systems', 'interactive-fiction', 'joshua');

  copyDir(SRC, enDir);
  copyDir(SRC, itDir);

  // English tree: boots English, switches to the Italian path, returns to "/".
  writeBuildConfig(enDir, {
    lang: 'en',
    langHref: '/it/human-systems/interactive-fiction/joshua/index.html',
    returnHref: '/',
    returnLabel: 'RETURN TO PIPPO.COM PERSONAL OPERATING SYSTEM'
  });
  // Italian tree: boots Italian, switches to the English path, returns to "/it/".
  writeBuildConfig(itDir, {
    lang: 'it',
    langHref: '/human-systems/interactive-fiction/joshua/index.html',
    returnHref: '/it/',
    returnLabel: 'TORNA AL PERSONAL OPERATING SYSTEM DI PIPPO.COM'
  });

  injectBuildConfigScript(path.join(enDir, 'index.html'));
  injectBuildConfigScript(path.join(itDir, 'index.html'));

  // Localized SEO/semantic metadata (title, description, canonical, hreflang,
  // Open Graph, inline JSON-LD) for the public pippo.com pages.
  injectSeoMetadata(path.join(enDir, 'index.html'), SEO.en);
  injectSeoMetadata(path.join(itDir, 'index.html'), SEO.it);

  return [enDir, itDir];
}

function writeBuildInfo(buildTypes) {
  const info = {
    version: version(),
    commit: gitShort('rev-parse --short HEAD'),
    builtAt: new Date().toISOString(),
    buildTypes: buildTypes,
    branch: gitShort('rev-parse --abbrev-ref HEAD')
  };
  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(path.join(DIST, 'build-info.json'), JSON.stringify(info, null, 2) + '\n');
  return info;
}

function packageStandalone() {
  const standalone = path.join(DIST, 'standalone');
  if (!fs.existsSync(path.join(standalone, 'index.html'))) {
    throw new Error('dist/standalone not built — run "node tools/build.js build" first');
  }
  const archive = path.join(DIST, `joshua-${version()}.tar.gz`);
  execSync(`tar -czf "${archive}" -C "${standalone}" .`, { cwd: ROOT, stdio: 'inherit' });
  return archive;
}

function main() {
  const command = process.argv[2] || 'build';
  switch (command) {
    case 'clean':
      rmrf(DIST);
      console.log('Removed dist/');
      return;
    case 'standalone':
      rmrf(DIST);
      buildStandalone();
      writeBuildInfo(['standalone']);
      console.log('Built dist/standalone/');
      return;
    case 'pippo':
      rmrf(DIST);
      buildPippo();
      writeBuildInfo(['pippo.com']);
      console.log('Built dist/pippo.com/ (EN + IT)');
      return;
    case 'package':
      console.log('Packaged ' + packageStandalone());
      return;
    case 'build':
      rmrf(DIST);
      buildStandalone();
      buildPippo();
      const info = writeBuildInfo(['standalone', 'pippo.com']);
      console.log('Built dist/standalone/');
      console.log('Built dist/pippo.com/ (EN + IT)');
      console.log('Wrote dist/build-info.json');
      return;
    default:
      console.error('Unknown command: ' + command);
      process.exit(1);
  }
}

main();
