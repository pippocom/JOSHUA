/*
 * JOSHUA Terminal build script. No runtime dependencies; uses Node's fs and
 * child_process (git) only.
 *
 * Produces a deterministic dist/ tree (except for intentionally variable
 * metadata: build timestamp and git commit/branch):
 *
 *   dist/standalone/                         — standalone single-document app
 *   dist/pippo.com/human-systems/interactive-fiction/joshua/   — EN pippo tree
 *   dist/pippo.com/it/human-systems/interactive-fiction/joshua/ — IT pippo tree
 *   dist/build-info.json                     — build metadata
 *
 * The standalone build is a straight copy of src/ (minus src/dev/). The
 * pippo.com builds are the same copy plus a generated buildConfig.js that
 * configures language/navigation; game.js reads window.JOSHUA_BUILD when
 * present (see src/app/game.js). No deployment, no upload, no credentials.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execSync } = require('node:child_process');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');

// Directories under src/ that must not ship in any build.
const EXCLUDE_DIRS = new Set(['dev']);

function version() {
  return JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
}

function gitShort(args) {
  try {
    return execSync(`git ${args}`, { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch (err) {
    return '';
  }
}

function rmrf(p) {
  fs.rmSync(p, { recursive: true, force: true });
}

function copyDir(srcDir, destDir) {
  fs.mkdirSync(destDir, { recursive: true });
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const s = path.join(srcDir, entry.name);
    const d = path.join(destDir, entry.name);
    if (entry.isDirectory()) {
      if (EXCLUDE_DIRS.has(entry.name)) continue;
      copyDir(s, d);
    } else {
      fs.copyFileSync(s, d);
    }
  }
}

function writeBuildConfig(destDir, config) {
  const js =
    '// Generated by tools/build.js. Deployment configuration for the pippo.com\n' +
    '// build; the standalone build ships no such file. See src/app/game.js.\n' +
    'window.JOSHUA_BUILD = ' + JSON.stringify(config, null, 2) + ';\n';
  fs.writeFileSync(path.join(destDir, 'buildConfig.js'), js);
}

function injectBuildConfigScript(htmlPath) {
  const marker = '<script src="app/game.js"></script>';
  const html = fs.readFileSync(htmlPath, 'utf8');
  if (html.includes('buildConfig.js')) return;
  fs.writeFileSync(htmlPath, html.replace(marker, '<script src="buildConfig.js"></script>\n  ' + marker));
}

